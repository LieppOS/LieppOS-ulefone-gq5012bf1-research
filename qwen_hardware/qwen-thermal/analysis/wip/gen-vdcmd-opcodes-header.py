#!/usr/bin/env python3
"""Generate the static vdcmd opcode registry from tested opcode evidence.

Input is the TSV produced by tools/extract-vdcmd-opcodes.py.  An opcode becomes a
`VDCMD_OPCODE_<BASE>` define (BASE = the verified payload helper name without its
`_get`/`_set` suffix) only when exactly one distinct base name is proven for it;
anything else becomes a commented-out slot, so the table stays dense and every
numeric hole stays greppable instead of silently becoming an unrelated name.
"""
from __future__ import annotations

import argparse
import csv
import pathlib
from collections import defaultdict

PREAMBLE = """/**
 * vdcmd-opcodes.h — generated; DO NOT EDIT.
 *
 * Static opcode registry for the vdcmd getter/setter table rebuilt from the
 * unstripped vendor payload helper libvdcmd_codec.so (ARM EABI5, BuildID
 * fd84421b0d740e6c3d629d422b7d3f4b0521e666).  Generated by
 * qwen-thermal/tools/gen-vdcmd-opcodes-header.py; per-opcode evidence is in the
 * TSV named below, and findings/vdm-opcode-recovery.md explains the method.
 *
 * The table is dense: VDCMD_OPCODE_COUNT is the exclusive upper bound, and an
 * opcode with no define is a hole whose status is written next to it:
 *   ambiguous  — more than one distinct helper name reaches that ID
 *   unproven   — only the transport reachability analysis mentions the ID
 * Never fill a hole from a guess; regenerate it from the binary instead.
 */
#ifndef VDCMD_OPCODES_H
#define VDCMD_OPCODES_H

"""

TRAILER = """
#define VDCMD_OPCODE_MIN 0x0000u
#define VDCMD_OPCODE_COUNT %d

#endif /* VDCMD_OPCODES_H */
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tsv", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--source", default="libircmd020.so")
    ap.add_argument("--source-md5", default="")
    ap.add_argument("--allow-holes", type=int, default=999,
                    help="fail if the dense table needs more than N hole comments")
    a = ap.parse_args()

    rows = list(csv.DictReader(pathlib.Path(a.tsv).read_text().splitlines(), delimiter="\t"))
    if not rows:
        raise SystemExit(f"no rows in {a.tsv}")

    helpers = defaultdict(set)      # opcode -> distinct base names (unique rows)
    reached = set()                 # opcodes mentioned anywhere in the evidence
    for row in rows:
        op = int(row["opcode"], 16)
        reached.add(op)
        if row["status"] == "unique":
            helpers[op].add(row["helper"].removesuffix("_get").removesuffix("_set"))
    max_op = max(reached)

    single = {op: next(iter(n)) for op, n in helpers.items() if len(n) == 1}
    ambiguous = sorted(op for op, n in helpers.items() if len(n) > 1)

    out = [PREAMBLE,
           f"/* Source binary: {a.source}" + (f" md5 {a.source_md5}" if a.source_md5 else "") + " */\n",
           f"/* Evidence: {a.tsv} — {len(single)} opcodes with exactly one proven name, "
           f"{len(reached)} reached IDs in total. */\n"]
    for op in sorted(single):
        op_name = single[op].upper()
        out.append(f"#define VDCMD_OPCODE_{op_name} 0x{op:04X}u\n")
    out.append("\n/* Ambiguous — reachable, but the payload helper name is not unique:\n")
    for op in ambiguous:
        out.append(f" * {op:#06x} " + ", ".join(sorted(helpers[op])) + "\n")
    out.append(" */\n")
    holes = 0
    out.append("\n/* Holes in the dense table:\n")
    for n in range(max_op + 1):
        if n not in single:
            why = "ambiguous" if n in reached else "unproven (transport reachability only)"
            out.append(f" * {n:#06x} {why}\n")
            holes += 1
    out.append(" */\n")
    out.append(TRAILER % (max_op + 1))

    if holes > a.allow_holes:
        raise SystemExit(f"{holes} holes exceeds --allow-holes {a.allow_holes}; table not dense")
    path = pathlib.Path(a.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(out))
    print(f"{path}: VDCMD_OPCODE_COUNT={max_op + 1} defined={len(single)} "
          f"ambiguous={len(ambiguous)} holes={holes} (defined+holes={len(single) + holes})")


if __name__ == "__main__":
    main()
