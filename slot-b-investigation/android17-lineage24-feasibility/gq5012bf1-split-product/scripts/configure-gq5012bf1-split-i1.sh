#!/bin/bash
set -o pipefail
TREE=/mnt/SamsungSSD/android/lineage-24.0
# Reuse the completed GSI OUT_DIR's shared intermediates. The new product has a
# separate target/product/gq5012bf1 directory; the generic_arm64 reference image
# is copied to /mnt/WDBlue first and hash-checked after every iteration.
OUT=out-android17-gsi-erofs
ART=/mnt/SamsungSSD/TIER3/phase5/android17
LOG="$ART/logs/configure-lineage_gq5012bf1-cp2a-userdebug-split-i1.log"
REPORT="$ART/reports/configure-lineage_gq5012bf1-split-i1.vars"
export OUT_DIR="$OUT"
export PATH="$ART/tools/git-lfs-3.8.0:$HOME/bin:$PATH"
cd "$TREE" || exit 125
{
  echo "START=$(date -Is)"
  echo 'COMMAND=source build/envsetup.sh'
  source build/envsetup.sh
  echo 'COMMAND=lunch lineage_gq5012bf1 cp2a userdebug'
  lunch lineage_gq5012bf1 cp2a userdebug
  rc=$?
  echo "LUNCH_EXIT=$rc"
  [ "$rc" -eq 0 ] || exit "$rc"
  WARN="$ART/logs/configure-lineage_gq5012bf1-split-i1-get-build-var-warnings.log"
  : > "$WARN"
  : > "$REPORT"
  vars='TARGET_PRODUCT TARGET_RELEASE TARGET_BUILD_VARIANT PLATFORM_VERSION PLATFORM_SDK_VERSION PLATFORM_SECURITY_PATCH LINEAGE_VERSION LINEAGE_BUILDTYPE PRODUCT_SHIPPING_API_LEVEL TARGET_ARCH TARGET_2ND_ARCH PRODUCT_OUT BOARD_SYSTEMIMAGE_FILE_SYSTEM_TYPE BOARD_PRODUCTIMAGE_FILE_SYSTEM_TYPE BOARD_SYSTEM_EXTIMAGE_FILE_SYSTEM_TYPE BOARD_SYSTEMIMAGE_PARTITION_SIZE BOARD_SYSTEM_EXTIMAGE_PARTITION_SIZE BOARD_PRODUCTIMAGE_PARTITION_SIZE BOARD_EROFS_COMPRESSOR BOARD_EROFS_PCLUSTER_SIZE TARGET_USERIMAGES_SPARSE_EROFS_DISABLED TARGET_COPY_OUT_PRODUCT TARGET_COPY_OUT_SYSTEM_EXT BOARD_USES_PRODUCTIMAGE BOARD_USES_SYSTEM_EXTIMAGE PRODUCT_BUILD_SYSTEM_IMAGE PRODUCT_BUILD_SYSTEM_EXT_IMAGE PRODUCT_BUILD_PRODUCT_IMAGE PRODUCT_BUILD_VENDOR_IMAGE PRODUCT_BUILD_BOOT_IMAGE PRODUCT_USE_DYNAMIC_PARTITIONS PRODUCT_USE_DYNAMIC_PARTITION_SIZE BOARD_SUPER_PARTITION_SIZE BOARD_SUPER_PARTITION_GROUPS BOARD_MAIN_PARTITION_LIST BOARD_MAIN_SIZE BOARD_AVB_ENABLE BOARD_AVB_VBMETA_SYSTEM BOARD_AVB_VBMETA_SYSTEM_KEY_PATH BOARD_AVB_VBMETA_SYSTEM_ALGORITHM BOARD_AVB_VBMETA_SYSTEM_ROLLBACK_INDEX_LOCATION BOARD_AVB_ROLLBACK_INDEX TARGET_NO_KERNEL WITH_DEXPREOPT PRODUCT_AVF_ENABLED PRODUCT_EXTRA_VNDK_VERSIONS BUILDING_GSI BUILDING_LINEAGE_GSI'
  for v in $vars; do
    value=$(get_build_var "$v" 2>>"$WARN")
    printf '%s=%s\n' "$v" "$value" | tee -a "$REPORT"
  done
  echo "END=$(date -Is)"
} 2>&1 | tee "$LOG"
exit ${PIPESTATUS[0]}
