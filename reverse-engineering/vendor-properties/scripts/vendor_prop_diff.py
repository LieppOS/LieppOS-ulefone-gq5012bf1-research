#!/usr/bin/env python3
"""Per-key vendor property ledger: stock vendor/odm/vendor_dlkm/odm_dlkm build.prop vs the LieppOS
device+vendor trees, with stock consumers (rg byte scan of every stock partition except *.prop).
usage: vendor_prop_diff.py <stock-partitions> <device-tree> <vendor-tree> <out.tsv> [out.prop]
Needs: rg (ripgrep). APK/JAR members are compressed and therefore not scanned (declared)."""
import collections, os, re, subprocess, sys
P, DT, VT, OUT = sys.argv[1:5]
FILES = ["vendor/build.prop", "vendor/odm/etc/build.prop", "vendor_dlkm/etc/build.prop", "odm_dlkm/etc/build.prop"]
props = collections.OrderedDict()
for f in FILES:
    for line in open(os.path.join(P, f), encoding="utf-8", errors="replace"):
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("import ") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        # last definition wins: init's LoadProperties overrides earlier values ("Overriding previous
        # property"), across files in load order (vendor -> odm -> vendor_dlkm -> odm_dlkm).
        # Stock vendor/build.prop repeats keys (e.g. ro.board.platform=common ... =mt6878).
        props.pop(k, None); props[k] = (v, f)
keys = list(props)
kf = "/tmp/vp-keys.txt"; open(kf, "w").write("\n".join(keys) + "\n")
out = subprocess.run(["rg", "-uuu", "-a", "-o", "-F", "-f", kf, "--with-filename", "-g", "!*.prop",
                      "vendor", "odm_dlkm", "vendor_dlkm", "system_ext", "system", "product"],
                     cwd=P, capture_output=True, text=True, errors="replace").stdout
cons = collections.defaultdict(set)
for l in out.splitlines():
    f, _, k = l.rpartition(":")
    if k in props:
        cons[k].add(f)
# definition sites in the LieppOS trees: makefiles + non-proprietary .prop/.rc only
defs = []
for root in (DT, VT):
    for dp, dn, fns in os.walk(root):
        dn[:] = [d for d in dn if d not in ("proprietary", "sepolicy", ".git")]
        for fn in fns:
            if fn.endswith((".mk", ".prop", ".rc")):
                defs.append(os.path.join(dp, fn))
txt = "".join(open(f, encoding="utf-8", errors="replace").read() for f in defs)
defined = {k for k in keys if re.search(r"(^|[\s'\"])" + re.escape(k) + r"\s*(=|\s)", txt, re.M)}
# stock RC files that set the key and are shipped by proprietary-files.txt
pf = set(l.split(";")[0].strip().lstrip("-") for l in open(os.path.join(DT, "proprietary-files.txt")) if l.strip() and not l.startswith("#"))
rcset = collections.defaultdict(set)
for part in ("vendor", "odm_dlkm", "vendor_dlkm"):
    for dp, dn, fns in os.walk(os.path.join(P, part)):
        for fn in fns:
            if fn.endswith(".rc"):
                f = os.path.join(dp, fn); rel = os.path.relpath(f, P)
                for m in re.finditer(r"^\s*setprop\s+(\S+)", open(f, errors="replace").read(), re.M):
                    if m.group(1) in props: rcset[m.group(1)].add((rel, rel in pf))
INHERIT = ("ro.virtual_ab.", "dalvik.vm.", "bluetooth.profile.", "ro.zygote", "ro.logd.", "ro.bionic.")
GEN = re.compile(r"^ro\.(product\.(vendor|odm|vendor_dlkm|odm_dlkm)\.|(vendor|odm|vendor_dlkm|odm_dlkm)\.build\.)")
def klass(k):
    if GEN.match(k) or k in ("ro.vendor.build.security_patch",): return "BUILD-GENERATED"
    if k.startswith("persist.log.tag"): return "LOG-TAG"
    if k.startswith(("vendor.debug.", "persist.vendor.debug", "debug.")): return "DEBUG"
    return "TUNABLE"
rows = []
for k, (v, f) in props.items():
    c = cons.get(k, set())
    ctx = sorted(x for x in c if "selinux" in x or x.endswith("_contexts"))
    real = sorted(x for x in c if x not in ctx)
    cl = klass(k)
    if cl == "BUILD-GENERATED": verdict = "GENERATED by build system"
    elif k in defined: verdict = "DEFINED in LieppOS tree"
    elif any(sh for _, sh in rcset.get(k, ())): verdict = "SET at runtime by shipped stock RC"
    elif k.startswith(INHERIT) and real: verdict = "CHECK: normally set by inherited AOSP product makefiles"
    elif cl in ("LOG-TAG", "DEBUG") and not real: verdict = "DROP-SAFE (debug/log, no stock consumer)"
    elif not real: verdict = "DROP-SAFE (no stock consumer found)"
    else: verdict = "MISSING in LieppOS tree (has stock consumer)"
    rows.append((k, v, f, cl, str(len(real)), ";".join(real[:6]) + (";..." if len(real) > 6 else ""), "yes" if ctx else "no", verdict, ";".join(sorted(r for r, _ in rcset.get(k, ())))))
with open(OUT, "w") as o:
    o.write("key\tstock_value\tstock_file\tclass\tconsumer_files\tconsumers\tin_sepolicy_contexts\tverdict\tstock_rc_setprop\n")
    for r in rows: o.write("\t".join(r) + "\n")
if len(sys.argv) > 5:   # installable .prop of the MISSING keys, grouped by stock file, stock order
    with open(sys.argv[5], "w") as o:
        o.write("# Generated by scripts/vendor_prop_diff.py: stock vendor-side properties with >=1 stock consumer\n"
                "# that no LieppOS device/vendor makefile, .prop or .rc defines. Effective (last-definition) values\n"
                "# from stock GQ5012BF1_EEA_V15. Install via TARGET_VENDOR_PROP (integration step).\n")
        cur = None
        for r in rows:
            if not r[7].startswith("MISSING"): continue
            if r[2] != cur: cur = r[2]; o.write(f"\n# ---- from stock {cur}\n")
            o.write(f"{r[0]}={r[1]}\n")
c = collections.Counter(r[7] for r in rows)
print(f"{len(rows)} keys from {len(FILES)} files")
for k, n in c.most_common(): print(f"  {n:4d}  {k}")
