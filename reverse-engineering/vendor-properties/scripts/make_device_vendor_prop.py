#!/usr/bin/env python3
"""Turn evidence/lieppos-vendor-missing.prop (stock-consumed vendor props absent from the LieppOS trees)
into the device-tree vendor.prop installed via TARGET_VENDOR_PROP. Every deviation from the research
list is declared here with its reason.
usage: make_device_vendor_prop.py <lieppos-vendor-missing.prop> <device-tree>/vendor.prop"""
import sys
SRC, OUT = sys.argv[1:3]
# Emitted into vendor/build.prop by build/make itself, or belong to another partition:
# duplicating them in TARGET_VENDOR_PROP is a duplicate-sysprop build error or a stale override.
DROP = {
    "ro.vendor.product.cpu.abilist": "generated (TARGET_CPU_ABI*)",
    "ro.vndk.version": "generated; forcing 34 would bind linkerconfig to a VNDK v34 apex",
    "ro.board.platform": "generated from TARGET_BOARD_PLATFORM=mt6878 (same value)",
    "ro.product.board": "generated from TARGET_BOOTLOADER_BOARD_NAME",
    "ro.build.ab_update": "generated (AB_OTA_UPDATER)",
    "ro.boot.dynamic_partitions": "generated (PRODUCT_USE_DYNAMIC_PARTITIONS)",
    "ro.hwui.use_vulkan": "generated (TARGET_USES_VULKAN); stock value empty",
    "ro.product.first_api_level": "generated from PRODUCT_SHIPPING_API_LEVEL=35 (same value)",
    "persist.sys.dalvik.vm.lib.2": "system partition (runtime_libart.mk)",
    "ro.cp_system_other_odex": "system partition (system_other dexpreopt)",
    "external_storage.casefold.enabled": "set by inherited emulated_storage.mk",
    "external_storage.sdcardfs.enabled": "set by inherited emulated_storage.mk",
    # payload not shipped by LieppOS
    "ro.gfx.driver.0": "com.mediatek.mt6878.gamedriver updatable-driver package is not shipped",
    # OEM identity / regional defaults / ROM policy, not hardware enablement
    "ro.system.custom.version": "Ulefone firmware identity string",
    "persist.sys.timezone": "EEA stock regional default (Europe/London)",
    "ro.control_privapp_permissions": "ROM policy; left to the LieppOS/Lineage product config",
}
# Values that name a payload LieppOS does not ship -> rewritten to the shipped equivalent.
REWRITE = {
    "ro.hardware.egl": ("mali", "stock 'meow' needs vendor/lib64/egl/libGLES_meow.so (MTK wrapper), not shipped; "
                                "LieppOS ships libGLES_mali.so (stock build.prop itself carried ro.hardware.egl?=mali)"),
}
kept = dropped = 0; lines = []
for l in open(SRC):
    s = l.strip()
    if not s or s.startswith("#"): continue
    k, v = s.split("=", 1)
    if k in DROP: dropped += 1; continue
    if k in REWRITE: lines.append(f"# {REWRITE[k][1]}"); v = REWRITE[k][0]
    lines.append(f"{k}={v}"); kept += 1
with open(OUT, "w") as o:
    o.write("# GQ5012BF1 vendor properties consumed by shipped stock vendor blobs.\n"
            "# Generated by ulefone-gq5012bf1-research/reverse-engineering/vendor-properties/scripts/\n"
            "# make_device_vendor_prop.py from evidence/lieppos-vendor-missing.prop (stock GQ5012BF1_EEA_V15\n"
            "# vendor/build.prop, effective = last definition). Do not edit by hand; regenerate.\n\n")
    o.write("\n".join(lines) + "\n")
print(f"{kept} kept, {dropped} dropped, {len(REWRITE)} rewritten")
