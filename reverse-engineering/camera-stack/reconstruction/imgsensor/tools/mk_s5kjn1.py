#!/usr/bin/env python3
"""Generate the s5kjn1 / s5kjn1cts / s5kjn1main2 sub-driver sources for the
GQ5012BF1 stock-parity imgsensor.ko rebuild.

There is no public source for these three drivers.  They were reconstructed
from the stock module:
  * data (pw_seq, mode tables, frame descriptors, static_ctx, ops, feature
    list) is regenerated byte-exact by scripts/gen_sensor_data.py;
  * sensor-init register writes come from stock-imgsensor-oracle/inline/
    *_open.tsv, extracted by scripts/inline_writes.py;
  * the shared MTK v4l2 boiler-plate functions (init_ctx, vsync_notify,
    *_seamless_switch, set_group_hold) are byte-identical to the
    source-backed imx989 driver, so they are copied from that file;
  * the vendor-specific logic (byte-order/offset ID probe, CTS gating, 4-cell
    EEPROM loader, streaming control, QSC) was written from the stock
    disassembly.

usage: mk_s5kjn1.py <imx989mipiraw_Sensor.c> <init.tsv> <variant> <outdir>
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.normpath(os.path.join(HERE, "../../../scripts"))


def grab(src, name):
    m = re.search(r"^static [^\n;]*\b" + name + r"\([^;{]*\)\n\{", src, re.M)
    i = m.start()
    j = src.index("\n}\n", i) + 3
    return src[i:j]


# --- per-variant get_imgsensor_id -------------------------------------------
# read(a, b): one chip-ID read attempt, (rd(a) << 8) | rd(b) plus a fix-up.
def id_attempt(v, first, second, expr_fix, gate):
    rd = f"(subdrv_i2c_rd_u8(ctx, {first}) << 8) |\n\t\t\t\tsubdrv_i2c_rd_u8(ctx, {second})"
    if expr_fix == "-1":
        val = f"((subdrv_i2c_rd_u8(ctx, {first}) << 8) |\n\t\t\t\tsubdrv_i2c_rd_u8(ctx, {second})) - 1"
    elif expr_fix == "+1":
        val = f"(subdrv_i2c_rd_u8(ctx, {first}) << 8) |\n\t\t\t\t(subdrv_i2c_rd_u8(ctx, {second}) + 1)"
    else:
        val = rd
    return f"""			*sensor_id = {val};
			printk("xqadd0 {v} i2c_write_id(0x%x) sensor_id(0x%x/0x%x)\\n",
				ctx->i2c_write_id, *sensor_id, ctx->s_ctx.sensor_id);
			if (*sensor_id == {v.upper()}_SENSOR_ID && {gate}) {{
				*sensor_id = ctx->s_ctx.sensor_id;
				return ERROR_NONE;
			}}
"""


VARIANTS = {
    # order: which register is read as the high byte on the first attempt
    "s5kjn1": dict(order=("addr_l", "addr_h"), fix="", cts=False, okss="drv",
                   seamless=True, fourcell="drv", stream=True, cali=False),
    "s5kjn1cts": dict(order=("addr_h", "addr_l"), fix="-1", cts=True, okss="drv",
                      seamless=False, fourcell=None, stream=True, cali=False),
    "s5kjn1main2": dict(order=("addr_h", "addr_l"), fix="+1", cts=False, okss="printk",
                        seamless=True, fourcell="printk", stream=False, cali=True),
}


def get_id(v, cfg):
    gate = "is_yft_cts_board() == 1" if cfg["cts"] else "!is_yft_cts_board()"
    fail = "is_yft_cts_board() != 1" if cfg["cts"] else "is_yft_cts_board()"
    a, b = cfg["order"]
    body = id_attempt(v, a, b, cfg["fix"], gate) + id_attempt(v, b, a, cfg["fix"], gate)
    if cfg["okss"] == "drv":
        okss = (f'\tDRV_LOG_MUST(ctx, "xqadd0 {v} okss i2c_write_id(0x%x) sensor_id(0x%x/0x%x)\\n",\n'
                "\t\tctx->i2c_write_id, *sensor_id, ctx->s_ctx.sensor_id);\n")
    else:
        okss = (f'\tprintk("xqadd0 {v} okss i2c_write_id(0x%x) sensor_id(0x%x/0x%x)\\n",\n'
                "\t\tctx->i2c_write_id, *sensor_id, ctx->s_ctx.sensor_id);\n")
    dh = "\tu32 addr_h = ctx->s_ctx.reg_addr_sensor_id.addr[0];\n"
    dl = "\tu32 addr_l = ctx->s_ctx.reg_addr_sensor_id.addr[1];\n"
    # declaration order only changes callee-saved register assignment
    decls = (dl + dh) if cfg["order"][0] == "addr_l" or cfg["fix"] == "+1" else (dh + dl)
    return f"""/*
 * Stock probes each i2c address twice per retry, swapping which of the two
 * chip-ID registers is taken as the high byte, then applies the YFT
 * CTS-board gate ({'CTS boards only' if cfg['cts'] else 'non-CTS boards only'}).
 */
static int get_imgsensor_id(struct subdrv_ctx *ctx, u32 *sensor_id)
{{
	u8 i = 0;
	u8 retry = 2;
{decls}
	while (ctx->s_ctx.i2c_addr_table[i] != 0xFF) {{
		ctx->i2c_write_id = ctx->s_ctx.i2c_addr_table[i];
		do {{
{body}			retry--;
		}} while (retry > 0);
		i++;
		retry = 2;
	}}
	if (*sensor_id != ctx->s_ctx.sensor_id || {fail}) {{
		*sensor_id = 0xFFFFFFFF;
		return ERROR_SENSOR_CONNECT_FAIL;
	}}
{okss}	return ERROR_NONE;
}}

"""


def fourcell(log):
    L = (lambda s, *a: f'DRV_LOG(ctx, {s}{"".join(", " + x for x in a)});') if log == "drv" else \
        (lambda s, *a: f'printk({s}{"".join(", " + x for x in a)});')
    return f"""static int read_4cell_from_eeprom(struct subdrv_ctx *ctx, u8 *para, u32 *len)
{{
	u64 *feature_data = (u64 *)para;
	char *data = (char *)(uintptr_t)(*(feature_data + 1));
	int ret;
	u8 temp = 0;

	{L('"xqadd0826 sub [%s] +"', '__func__')}
	if (*data == 0)
		printk("SENSOR_FEATURE_GET_4CELL_DATA feature_data=%d\\n", *data);

	/* Check I2C is normal */
	ret = adaptor_i2c_rd_u8(ctx->i2c_client, EEPROM_READ_ID >> 1, 0x0D4F, &temp);
	if (ret != 0) {{
		printk("iReadRegI2C error");
		return ret;
	}}

	if (!Is_Read_4Cell) {{
		printk("Need to read i2C");
		Four_Cell_Array[0] = (FOUR_CELL_SIZE & 0xff);/*Low*/
		Four_Cell_Array[1] = ((FOUR_CELL_SIZE >> 8) & 0xff);/*High*/
		adaptor_i2c_rd_p8(ctx->i2c_client, EEPROM_READ_ID >> 1, 0x0D4F,
			&Four_Cell_Array[2], FOUR_CELL_SIZE_XTC);
		memset(&Four_Cell_Array[3504], 0, 594);
		adaptor_i2c_rd_p8(ctx->i2c_client, EEPROM_READ_ID >> 1, 0x1AFD,
			&Four_Cell_Array[4098], FOUR_CELL_SIZE_SENSOR_XTC);
		adaptor_i2c_rd_p8(ctx->i2c_client, EEPROM_READ_ID >> 1, 0x1DFD,
			&Four_Cell_Array[4866], FOUR_CELL_SIZE_PDXTC);
		adaptor_i2c_rd_p8(ctx->i2c_client, EEPROM_READ_ID >> 1, 0x2D9D,
			&Four_Cell_Array[8866], FOUR_CELL_SIZE_SW_GGC);
		Is_Read_4Cell = 1;
		{L('"[%s] +"', '__func__')}
	}}

	if (data != NULL) {{
		{L('"return data\\n"')}
		memcpy(data, Four_Cell_Array, FOUR_CELL_SIZE + 2);
	}}
	return ret;
}}

"""


FOURCELL_DEFS = """#define EEPROM_READ_ID		0xA0
#define FOUR_CELL_SIZE		9490
#define FOUR_CELL_SIZE_XTC	3502
#define FOUR_CELL_SIZE_SENSOR_XTC	768
#define FOUR_CELL_SIZE_PDXTC	4000
#define FOUR_CELL_SIZE_SW_GGC	626

static bool Is_Read_4Cell;
static char Four_Cell_Array[FOUR_CELL_SIZE + 2];

"""

CALI = """static void set_sensor_cali(void *arg)
{
	struct subdrv_ctx *ctx = (struct subdrv_ctx *)arg;

	u16 idx = 0;
	u8 support = FALSE;
	u8 *pbuf = NULL;
	u16 size = 0;
	u16 addr = 0;
	struct eeprom_info_struct *info = ctx->s_ctx.eeprom_info;

	if (!probe_eeprom(ctx))
		return;

	idx = ctx->eeprom_index;

	/* QSC data */
	support = info[idx].qsc_support;
	pbuf = info[idx].preload_qsc_table;
	size = info[idx].qsc_size;
	addr = info[idx].sensor_reg_addr_qsc;
	if (support) {
		if (pbuf != NULL && addr > 0 && size > 0) {
			subdrv_i2c_wr_seq_p8(ctx, addr, pbuf, size);
			DRV_LOG(ctx, "set QSC calibration data done.  ");
		} else {
			DRV_LOG(ctx, "qsc unsupport .");
		}
	}
}

"""

STREAM = """static void custom_streaming_control(struct subdrv_ctx *ctx, bool enable)
{
	subdrv_i2c_wr_u8(ctx, 0x0100, enable);
	mdelay(10);
}

static int streaming_control_off(struct subdrv_ctx *ctx, u8 *para, u32 *len)
{
	custom_streaming_control(ctx, FALSE);
	return ERROR_NONE;
}

static int streaming_control_on(struct subdrv_ctx *ctx, u8 *para, u32 *len)
{
	custom_streaming_control(ctx, TRUE);
	return ERROR_NONE;
}
"""


def main():
    imx, tsv, v, out = sys.argv[1:5]
    cfg = VARIANTS[v]
    src = open(imx).read()
    head = src[:src.index('#include "imx989mipiraw_Sensor.h"')].replace("imx989", v)
    init = subprocess.run([sys.executable, os.path.join(SCRIPTS, "inline_to_c.py"), tsv],
                          capture_output=True, text=True, check=True).stdout.rstrip("\n")
    openf = grab(src, "open")
    openf = openf.replace("""	/* initail setting */
	sensor_init(ctx);

	if (ctx->s_ctx.s_cali != NULL)
		ctx->s_ctx.s_cali((void *) ctx);
	else
		write_sensor_Cali(ctx);
""", f"""	/* initail setting */
	{v}_sensor_init(ctx);
""")
    k = openf.index("\tif (ctx->s_ctx.mode[ctx->current_scenario_id].hdr_mode == HDR_RAW_LBMF)")
    openf = openf[:k].rstrip("\n") + "\n\n\treturn ERROR_NONE;\n}\n"

    protos = ["static int get_imgsensor_id(struct subdrv_ctx *ctx, u32 *sensor_id);",
              "static int open(struct subdrv_ctx *ctx);"]
    if cfg["cali"]:
        protos.append("static void set_sensor_cali(void *arg);")
    protos += ["static void set_group_hold(void *arg, u8 en);", "static u16 get_gain2reg(u32 gain);"]
    if cfg["seamless"]:
        protos.append(f"static int {v}_seamless_switch(struct subdrv_ctx *ctx, u8 *para, u32 *len);")
    protos += [f"static int {v}_set_test_pattern(struct subdrv_ctx *ctx, u8 *para, u32 *len);",
               f"static int {v}_set_test_pattern_data(struct subdrv_ctx *ctx, u8 *para, u32 *len);"]
    if cfg["fourcell"]:
        protos.append("static int read_4cell_from_eeprom(struct subdrv_ctx *ctx, u8 *para, u32 *len);")
    if cfg["stream"]:
        protos += ["static int streaming_control_off(struct subdrv_ctx *ctx, u8 *para, u32 *len);",
                   "static int streaming_control_on(struct subdrv_ctx *ctx, u8 *para, u32 *len);"]
    protos += ["static int init_ctx(struct subdrv_ctx *ctx,\tstruct i2c_client *i2c_client, u8 i2c_write_id);",
               "static int vsync_notify(struct subdrv_ctx *ctx,\tunsigned int sof_cnt);"]

    c = head + f'#include "{v}mipiraw_Sensor.h"\n\n' + "\n".join(protos) + "\n\n"
    c += "/* STOCK-PARITY data: regenerated byte-exact from the GQ5012BF1 stock module */\n"
    c += f'#ifdef GQ5012BF1_CAM_CORRECTED\n/* CORRECTED: mode/frame-descriptor geometry fixed (reconstruction/imgsensor/corrected/) */\n#include "{v}_corrected_data.h"\n#else\n#include "{v}_stock_data.h"\n#endif\n\n'
    if cfg["fourcell"]:
        c += FOURCELL_DEFS
    c += "/* FUNCTION */\n\n"
    c += get_id(v, cfg)
    c += grab(src, "init_ctx") + "\n"
    c += f"""static void {v}_sensor_init(struct subdrv_ctx *ctx)
{{
	DRV_LOG(ctx, "E\\n");
	DRV_LOG(ctx, "Dphy-4lane setting\\n");
{init}
	DRV_LOG(ctx, "X\\n");
}}

"""
    c += openf + "\n" + grab(src, "vsync_notify") + "\n"
    c += """static u16 get_gain2reg(u32 gain)
{
	return gain * 32 / BASEGAIN;
}

"""
    c += grab(src, "set_group_hold") + "\n"
    if cfg["cali"]:
        c += CALI
    c += f"""static int {v}_set_test_pattern(struct subdrv_ctx *ctx, u8 *para, u32 *len)
{{
	u32 mode = *((u32 *)para);

	if (mode != ctx->test_pattern)
		DRV_LOG(ctx, "mode(%u->%u)\\n", ctx->test_pattern, mode);
	/* 1:Solid Color 2:Color Bar 5:Black */
	if (mode)
		subdrv_i2c_wr_u16(ctx, 0x0600, mode); /*100% Color bar*/
	else if (ctx->test_pattern)
		subdrv_i2c_wr_u16(ctx, 0x0600, 0x0000); /*No pattern*/

	ctx->test_pattern = mode;
	return ERROR_NONE;
}}

static int {v}_set_test_pattern_data(struct subdrv_ctx *ctx, u8 *para, u32 *len)
{{
	struct mtk_test_pattern_data *data = (struct mtk_test_pattern_data *)para;
	u16 R = (data->Channel_R >> 22) & 0x3ff;
	u16 Gr = (data->Channel_Gr >> 22) & 0x3ff;
	u16 Gb = (data->Channel_Gb >> 22) & 0x3ff;
	u16 B = (data->Channel_B >> 22) & 0x3ff;

	subdrv_i2c_wr_u16(ctx, 0x0602, R);
	subdrv_i2c_wr_u16(ctx, 0x0604, Gr);
	subdrv_i2c_wr_u16(ctx, 0x0606, B);
	subdrv_i2c_wr_u16(ctx, 0x0608, Gb);

	DRV_LOG(ctx, "mode(%u) R/Gr/Gb/B = 0x%04x/0x%04x/0x%04x/0x%04x\\n",
		ctx->test_pattern, R, Gr, Gb, B);
	return ERROR_NONE;
}}

"""
    if cfg["seamless"]:
        c += grab(src, "imx989_seamless_switch").replace("imx989", v) + "\n"
    if cfg["fourcell"]:
        c += fourcell(cfg["fourcell"])
    if cfg["stream"]:
        c += STREAM
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, f"{v}mipiraw_Sensor.c"), "w").write(c.rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
